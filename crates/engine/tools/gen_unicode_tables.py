#!/usr/bin/env python3
"""Generates crates/engine/src/unicode/tables.rs, the Unicode normalization tables.

Usage: python gen_unicode_tables.py <ucd-dir> <output.rs>

<ucd-dir> holds UnicodeData.txt and CompositionExclusions.txt from
https://www.unicode.org/Public/<version>/ucd/ . The tables hold:

- canonical combining classes (ranges of equal non-zero class),
- full (recursively applied) canonical and compatibility decompositions, Hangul
  syllables excluded (they are decomposed algorithmically),
- canonical compositions (primary composites only), Hangul excluded.
"""

import re
import sys


def main(ucd, out):
    ccc = {}
    decomp = {}  # code point -> (compat: bool, [code points]), one level
    version = None
    for line in open(f"{ucd}/UnicodeData.txt", encoding="utf-8"):
        f = line.rstrip("\n").split(";")
        cp = int(f[0], 16)
        if f[1].endswith(", Last>"):
            continue  # ranges (CJK, Hangul, ...) have class 0 and no decomposition
        if int(f[3]):
            ccc[cp] = int(f[3])
        if f[5]:
            parts = f[5].split()
            compat = parts[0].startswith("<")
            if compat:
                parts = parts[1:]
            decomp[cp] = (compat, [int(p, 16) for p in parts])

    excluded = set()
    for line in open(f"{ucd}/CompositionExclusions.txt", encoding="utf-8"):
        if version is None:
            m = re.match(r"# CompositionExclusions-(\d+\.\d+\.\d+)\.txt", line)
            if m:
                version = m.group(1)
        line = line.split("#")[0].strip()
        if line:
            excluded.add(int(line.split("..")[0], 16))

    def full(cp, compat):
        d = decomp.get(cp)
        if d is None or (d[0] and not compat):
            return [cp]
        return [c for p in d[1] for c in full(p, compat)]

    canon = {cp: full(cp, False) for cp, (c, _) in decomp.items() if not c}
    compat = {}
    for cp in decomp:
        f = full(cp, True)
        if f != canon.get(cp):
            compat[cp] = f  # only where it differs from the canonical decomposition

    compose = []
    for cp, (c, parts) in decomp.items():
        if c or len(parts) != 2 or cp in excluded or ccc.get(cp, 0) or ccc.get(parts[0], 0):
            continue  # singletons, exclusions and non-starter decompositions don't compose
        compose.append((parts[0], parts[1], cp))
    compose.sort()

    ranges = []
    for cp in sorted(ccc):
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == ccc[cp]:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, ccc[cp]])

    def ch(cp):
        return f"'\\u{{{cp:X}}}'"

    def decomp_table(name, table):
        data, rows = [], []
        for cp in sorted(table):
            rows.append(f"({ch(cp)}, {len(data)}, {len(table[cp])})")
            data.extend(table[cp])
        assert len(data) < 1 << 16 and max(map(len, table.values())) < 1 << 8
        return (
            f"/// Full {name.lower()} decompositions: (char, start, length) into `{name}_CHARS`.\n"
            f"#[rustfmt::skip]\npub(super) static {name}: &[(char, u16, u8)] = &[\n{wrap(rows)}];\n\n"
            f"#[rustfmt::skip]\npub(super) static {name}_CHARS: &[char] = &[\n{wrap([ch(c) for c in data])}];\n\n"
        )

    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write(
            f"//! Unicode {version} normalization tables. Generated by\n"
            "//! `crates/engine/tools/gen_unicode_tables.py`; do not edit.\n\n"
            f"/// The Unicode version of these tables.\n#[cfg(test)]\npub(super) const UNICODE_VERSION: &str = \"{version}\";\n\n"
            "/// Canonical combining classes: (first, last, class) ranges; unlisted chars are 0.\n"
            "#[rustfmt::skip]\npub(super) static COMBINING_CLASS: &[(char, char, u8)] = &[\n"
            + wrap([f"({ch(a)}, {ch(b)}, {c})" for a, b, c in ranges])
            + "];\n\n"
            + decomp_table("CANONICAL", canon)
            + decomp_table("COMPAT", compat)
            + "/// Canonical compositions: (first, second, composite), sorted.\n"
            "#[rustfmt::skip]\npub(super) static COMPOSITION: &[(char, char, char)] = &[\n"
            + wrap([f"({ch(a)}, {ch(b)}, {ch(c)})" for a, b, c in compose])
            + "];\n"
        )


def wrap(items, width=100):
    lines, cur = [], "   "
    for it in items:
        if len(cur) + len(it) + 2 > width:
            lines.append(cur)
            cur = "   "
        cur += f" {it},"
    if cur.strip():
        lines.append(cur)
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
